/** @param {string} templateId */
export function getEditorKeysForTemplateId(templateId) {
  const id = String(templateId || "").trim();
  if (!id) return null;
  const t = POPUP_READY_TEMPLATES.find((x) => x.id === id);
  return t?.editorKeys ?? null;
}

/** @param {string} designTemplateId */
export function getPopupTemplateMeta(designTemplateId) {
  const id = String(designTemplateId || "").trim();
  if (!id) return null;
  return POPUP_READY_TEMPLATES.find((x) => x.id === id) ?? null;
}
